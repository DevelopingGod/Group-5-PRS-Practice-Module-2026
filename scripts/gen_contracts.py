"""Regenerate every artefact derived from the contracts package.

Outputs (committed, and checked for drift in CI):
  contracts/generated/openapi.json
  contracts/generated/*.schema.json
  apps/web/src/contracts/constants.ts
  apps/web/src/contracts/bin-qr.schema.json
TypeScript API types are then generated from openapi.json by `pnpm gen:types`.
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

from binbuddy_contracts import constants
from binbuddy_contracts.api import BinQrPayload
from binbuddy_contracts.dataset import COLUMNS, LabelRow
from binbuddy_contracts.enums import Channel, Condition, Material
from binbuddy_contracts.openapi import build_contract_app
from binbuddy_contracts.policy import SitePolicy
from binbuddy_contracts.questions import OPENING_QUESTION, QUESTION_BANK

ROOT = Path(__file__).resolve().parents[1]
GEN = ROOT / "contracts" / "generated"
WEB = ROOT / "apps" / "web" / "src" / "contracts"
HEADER = "// GENERATED by scripts/gen_contracts.py - do not edit by hand.\n"


def _write_json(path: Path, data: Any) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(data, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")


def _constants_ts() -> str:
    values = {
        "CONTRACTS_VERSION": constants.CONTRACTS_VERSION,
        "DEFAULT_SITE_POLICY": constants.DEFAULT_SITE_POLICY,
        "EMBEDDING_DIM": constants.EMBEDDING_DIM,
        "MAX_IMAGE_BYTES": constants.MAX_IMAGE_BYTES,
        "CONFIDENCE_THRESHOLD": constants.CONFIDENCE_THRESHOLD,
        "VERIFY_TIME_WINDOW_MINUTES": constants.VERIFY_TIME_WINDOW_MINUTES,
        "VERIFY_MIN_SIMILARITY": constants.VERIFY_MIN_SIMILARITY,
        "POINTS_PER_VERIFIED_DISPOSAL": constants.POINTS_PER_VERIFIED_DISPOSAL,
        "DAILY_POINTS_CAP": constants.DAILY_POINTS_CAP,
    }
    lines = [HEADER]
    for name, value in values.items():
        lines.append(f"export const {name} = {json.dumps(value)} as const;\n")
    for enum_name, enum in (
        ("MATERIALS", Material),
        ("CONDITIONS", Condition),
        ("CHANNELS", Channel),
    ):
        items = ", ".join(json.dumps(v.value) for v in enum)
        lines.append(f"export const {enum_name} = [{items}] as const;\n")
    bank = {
        qid.value: {"text": spec.text, "options": list(spec.options)}
        for qid, spec in QUESTION_BANK.items()
    }
    lines.append(
        f"export const OPENING_QUESTION = {json.dumps(OPENING_QUESTION.value)} as const;\n"
    )
    lines.append(f"export const QUESTION_BANK = {json.dumps(bank, indent=2)} as const;\n")
    return "".join(lines)


def main() -> None:
    _write_json(GEN / "openapi.json", build_contract_app().openapi())
    _write_json(GEN / "bin_qr.schema.json", BinQrPayload.model_json_schema())
    _write_json(GEN / "site_policy.schema.json", SitePolicy.model_json_schema())
    _write_json(
        GEN / "label_row.schema.json",
        {"columns": list(COLUMNS), "row": LabelRow.model_json_schema()},
    )
    _write_json(WEB / "bin-qr.schema.json", BinQrPayload.model_json_schema())
    (WEB / "constants.ts").write_text(_constants_ts(), encoding="utf-8")
    print("contracts regenerated")


if __name__ == "__main__":
    main()
