-- Scans and profiles are written only by the server (route handlers, service role).
-- Owner: WS4. A browser-written scan could carry a forged verdict or embedding and later
-- earn points through /verify, so users keep read access to their own rows only.

-- A scan is saved right after /predict; when questions are needed the channel is not known
-- yet, so it stays null until /answer returns the verdict.
alter table scans alter column channel drop not null;

drop policy "own scans" on scans;
create policy "own scans read" on scans for select using (auth.uid() = user_id);

-- Pseudonyms are generated by the server, so users cannot choose an identifying name.
drop policy "own profile" on profiles;
create policy "own profile read" on profiles for select using (auth.uid() = id);
